// protoc-gen-grpc-mock is a protoc plugin that generates mock server implementations
// for gRPC services. The generated mocks can be used with the mocker package to
// replay recorded gRPC interactions.
//
// Usage:
//
//	protoc --grpc-mock_out=. your_service.proto
//
// Or with buf:
//
//	buf generate
package main

import (
	"fmt"

	"google.golang.org/protobuf/compiler/protogen"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}
			generateFile(gen, f)
		}
		return nil
	})
}

func svcName(svc *protogen.Service) string {
	return "mock" + svc.GoName
}

func getMarshalPkg(g *protogen.GeneratedFile) string {
	return g.QualifiedGoIdent(
		protogen.GoIdent{
			GoName:       "Marshal",
			GoImportPath: protogen.GoImportPath("google.golang.org/protobuf/encoding/protojson"),
		},
	)
}

func getUnmarshalPkg(g *protogen.GeneratedFile) string {
	return g.QualifiedGoIdent(
		protogen.GoIdent{
			GoName:       "Unmarshal",
			GoImportPath: protogen.GoImportPath("google.golang.org/protobuf/encoding/protojson"),
		},
	)
}

func getMockServer(g *protogen.GeneratedFile) string {
	return g.QualifiedGoIdent(
		protogen.GoIdent{
			GoName:       "MockServer",
			GoImportPath: protogen.GoImportPath("github.com/ankurs/grpc-mock/mocker"),
		},
	)
}

func getCtx(g *protogen.GeneratedFile) string {
	return g.QualifiedGoIdent(
		protogen.GoIdent{
			GoName:       "Context",
			GoImportPath: protogen.GoImportPath("context"),
		},
	)
}

func generateFile(gen *protogen.Plugin, file *protogen.File) {
	if len(file.Services) == 0 {
		return
	}

	filename := file.GeneratedFilenamePrefix + ".mock.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)

	g.P("// Code generated by protoc-gen-grpc-mock. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()

	for _, svc := range file.Services {
		if len(svc.Methods) == 0 {
			continue
		}

		sName := svcName(svc)

		// Generate struct documentation
		g.P("// ", sName, " is a mock implementation of ", svc.GoName, "Server.")
		g.P("// It uses recorded interactions to replay responses.")
		g.P("type ", sName, " struct {")
		g.P("	", getMockServer(g))
		g.P("}")
		g.P()

		for _, m := range svc.Methods {
			ctx := getCtx(g)
			input := g.QualifiedGoIdent(m.Input.GoIdent)
			output := g.QualifiedGoIdent(m.Output.GoIdent)

			// Handle streaming methods
			if m.Desc.IsStreamingClient() || m.Desc.IsStreamingServer() {
				g.P("// ", m.GoName, " is a streaming RPC method.")
				g.P("// Note: Streaming is not yet supported, this method returns nil.")
				g.P(fmt.Sprintf("func (m *%s) %s(_ %s_%sServer) error {", sName, m.GoName, svc.GoName, m.GoName))
				g.P("	return nil")
				g.P("}")
				g.P()
				continue
			}

			// Generate unary method
			g.P("// ", m.GoName, " handles the ", svc.GoName, ".", m.GoName, " RPC.")
			g.P(fmt.Sprintf("func (m *%s) %s(ctx %s, input *%s) (*%s, error) {", sName, m.GoName, ctx, input, output))

			mar := getMarshalPkg(g)
			unmar := getUnmarshalPkg(g)

			g.P("	req, err := ", mar, "(input)")
			g.P("	if err != nil {")
			g.P("		return nil, err")
			g.P("	}")
			g.P()
			g.P(fmt.Sprintf("	resp, err := m.Serve(ctx, %q, %q, req)", svc.GoName, m.GoName))
			g.P("	if err != nil {")
			g.P("		return nil, err")
			g.P("	}")
			g.P()
			g.P("	output := &", output, "{}")
			g.P("	if err := ", unmar, "(resp, output); err != nil {")
			g.P("		return nil, err")
			g.P("	}")
			g.P()
			g.P("	return output, nil")
			g.P("}")
			g.P()
		}

		// Generate factory function
		g.P("// MakeMock", svc.GoName, "Server creates a new mock ", svc.GoName, "Server from the given MockServer.")
		g.P("// The MockServer should be created using mocker.NewMocker with a recorded interactions file.")
		g.P(fmt.Sprintf("func MakeMock%sServer(mock %s) %sServer {", svc.GoName, getMockServer(g), svc.GoName))
		g.P(fmt.Sprintf("	return &%s{mock}", sName))
		g.P("}")
		g.P()
	}
}
